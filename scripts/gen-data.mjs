// Compiles repository data into Convex modules and copies the shipped art.
// Ported from Amayi Learn (scripts/gen-data.mjs at ec3496e).
//
// Convex functions cannot read repository files at runtime, so the prompts in
// convex/ai/prompts and the mock fixtures in tests/fixtures/ai are written into
// convex/data/*.generated.ts here. Run by pnpm gen, which runs before lint,
// test, typecheck and build. Fixtures are included unless
// TAKU_GEN_FIXTURES=0 (production builds).
//
// Art: the WebP files in art/assets (committed by Codex, art/STYLE.md) are
// copied to public/art, and src/art.generated.ts lists which slugs exist, so
// ImageSlot shows a labelled placeholder for any image not made yet.

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "convex", "data");

// Byte identical to canonicalJson in convex/lib/canonical.ts.
export function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map((v) => canonicalJson(v)).join(",")}]`;
  const entries = Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(",")}}`;
}

export function sha256Hex(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function read(path) {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

function listFiles(dir, predicate = () => true) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isFile() && predicate(name))
    .sort();
}

function listDirs(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory())
    .sort();
}

function rel(path) {
  return relative(ROOT, path).split("\\").join("/");
}

function tsModule(header, exports) {
  const lines = ["// GENERATED by scripts/gen-data.mjs. Do not edit by hand. Run pnpm gen.", header, ""];
  for (const [name, type, value] of exports) {
    lines.push(`export const ${name}: ${type} = ${JSON.stringify(value, null, 1)};`, "");
  }
  // Non ASCII characters are written as escapes so generated files carry no
  // dash characters and stay byte stable across editors.
  return lines.join("\n").replace(/[^\t\n\r -~]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return false;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf8");
  return true;
}

export function buildFixtures() {
  const fixtures = {};
  const aiDir = join(ROOT, "tests", "fixtures", "ai");
  for (const purpose of listDirs(aiDir)) {
    for (const name of listFiles(join(aiDir, purpose), (n) => n.endsWith(".json"))) {
      const path = join(aiDir, purpose, name);
      const f = JSON.parse(read(path));
      if (f.keyMaterial === undefined || f.response === undefined) throw new Error(`${rel(path)} needs keyMaterial and response.`);
      const key = sha256Hex(canonicalJson(f.keyMaterial)).slice(0, 16);
      const id = `${purpose}/${key}`;
      if (fixtures[id] !== undefined) throw new Error(`${rel(path)} duplicates the key of ${fixtures[id].source}.`);
      fixtures[id] = { ...f.response, source: rel(path) };
    }
  }
  return fixtures;
}

export function buildArt() {
  const from = join(ROOT, "art", "assets");
  const to = join(ROOT, "public", "art");
  const slugs = listFiles(from, (n) => n.endsWith(".webp")).map((n) => n.replace(/\.webp$/, ""));
  mkdirSync(to, { recursive: true });
  for (const slug of slugs) {
    const src = join(from, `${slug}.webp`);
    const dst = join(to, `${slug}.webp`);
    if (!existsSync(dst) || statSync(dst).size !== statSync(src).size) copyFileSync(src, dst);
  }
  const body = `// GENERATED by scripts/gen-data.mjs. Do not edit by hand. Run pnpm gen.\nexport const ART_SLUGS: readonly string[] = ${JSON.stringify(slugs)};\n`;
  return writeIfChanged(join(ROOT, "src", "art.generated.ts"), body);
}

export function build() {
  const prompts = {};
  for (const name of listFiles(join(ROOT, "convex", "ai", "prompts"), (n) => n.endsWith(".md"))) {
    prompts[name.replace(/\.md$/, "")] = read(join(ROOT, "convex", "ai", "prompts", name));
  }
  const includeFixtures = process.env.TAKU_GEN_FIXTURES !== "0";
  const fixtures = includeFixtures ? buildFixtures() : {};
  const a = writeIfChanged(join(OUT_DIR, "generated.ts"), tsModule("", [["PROMPTS", "Record<string, string>", prompts]]));
  const b = writeIfChanged(
    join(OUT_DIR, "fixtures.generated.ts"),
    tsModule('import type { AiFixture } from "./types";', [["AI_FIXTURES", "Record<string, AiFixture>", fixtures]]),
  );
  const c = buildArt();
  return { changed: a || b || c, prompts: Object.keys(prompts).length, fixtures: Object.keys(fixtures).length, includeFixtures };
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const summary = build();
  console.log(
    `gen: ${summary.prompts} prompts, ${summary.fixtures} AI fixtures${summary.includeFixtures ? "" : " (fixtures excluded)"}${summary.changed ? "" : " (unchanged)"}`,
  );
}
