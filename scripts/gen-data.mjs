// Compiles repository data into Convex modules and copies the shipped art.
// Ported from Amayi Learn (scripts/gen-data.mjs at ec3496e).
//
// Convex functions cannot read repository files at runtime, so the prompts in
// convex/ai/prompts and the mock fixtures in tests/fixtures/ai are written into
// convex/data/*.generated.ts here. Run by pnpm gen, which runs before lint,
// test, typecheck and build. Fixtures are included unless
// TAKU_GEN_FIXTURES=0 (production builds).
//
// Art: the web sizes in art/web (made by art/web/build_web.py from the
// cutouts and scenes Codex committed), the decor, the surface textures (made
// by tools/make-textures.py) and any raster objects in art/objects are copied
// to public/art, and src/art.generated.ts lists each image with its sizes.

import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parse as parseYaml } from "yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(ROOT, "convex", "data");

// Byte identical to canonicalJson in convex/lib/canonical.ts.
export function canonicalJson(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map((v) => canonicalJson(v)).join(",")}]`;
  const entries = Object.entries(value)
    .filter(([, v]) => v !== undefined)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(",")}}`;
}

export function sha256Hex(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function read(path) {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

function listFiles(dir, predicate = () => true) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isFile() && predicate(name))
    .sort();
}

function listDirs(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory())
    .sort();
}

function rel(path) {
  return relative(ROOT, path).split("\\").join("/");
}

function tsModule(header, exports) {
  const lines = ["// GENERATED by scripts/gen-data.mjs. Do not edit by hand. Run pnpm gen.", header, ""];
  for (const [name, type, value] of exports) {
    lines.push(`export const ${name}: ${type} = ${JSON.stringify(value, null, 1)};`, "");
  }
  // Non ASCII characters are written as escapes so generated files carry no
  // dash characters and stay byte stable across editors.
  return lines.join("\n").replace(/[^\t\n\r -~]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`);
}

function writeIfChanged(path, content) {
  if (existsSync(path) && readFileSync(path, "utf8") === content) return false;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, "utf8");
  return true;
}

export function buildFixtures() {
  const fixtures = {};
  const aiDir = join(ROOT, "tests", "fixtures", "ai");
  for (const purpose of listDirs(aiDir)) {
    for (const name of listFiles(join(aiDir, purpose), (n) => n.endsWith(".json"))) {
      const path = join(aiDir, purpose, name);
      const f = JSON.parse(read(path));
      if (f.keyMaterial === undefined || f.response === undefined) throw new Error(`${rel(path)} needs keyMaterial and response.`);
      const key = sha256Hex(canonicalJson(f.keyMaterial)).slice(0, 16);
      const id = `${purpose}/${key}`;
      if (fixtures[id] !== undefined) throw new Error(`${rel(path)} duplicates the key of ${fixtures[id].source}.`);
      fixtures[id] = { ...f.response, source: rel(path) };
    }
  }
  return fixtures;
}

function copyDir(from, to, predicate) {
  mkdirSync(to, { recursive: true });
  for (const name of listFiles(from, predicate)) {
    const src = join(from, name);
    const dst = join(to, name);
    if (!existsSync(dst) || statSync(dst).size !== statSync(src).size) copyFileSync(src, dst);
  }
}

/** The surfaces in use (tools/make-textures.py). The older wave and grain files are in art/archive/textures and do not ship. */
const TEXTURES = ["paper-cotton.webp", "bookcloth-honey.webp", "linen-charcoal.webp"];

export function buildArt() {
  const to = join(ROOT, "public", "art");
  // Web sizes made by art/web/build_web.py from the cutouts and scenes, plus decor and textures as committed.
  copyDir(join(ROOT, "art", "web", "cutouts"), join(to, "cutouts"), (n) => n.endsWith(".webp"));
  copyDir(join(ROOT, "art", "web", "scenes"), join(to, "scenes"), (n) => n.endsWith(".webp"));
  copyDir(join(ROOT, "art", "web"), to, (n) => n === "og-landing.jpg");
  copyDir(join(ROOT, "art", "decor"), join(to, "decor"), (n) => n.endsWith(".webp") || n.endsWith(".svg"));
  copyDir(join(ROOT, "art", "textures"), join(to, "textures"), (n) => TEXTURES.includes(n));
  // Raster objects (Codex, art/BRIEF-batch-4.md) replace the inline SVG in src/components/ObjectArt.tsx one by one.
  // Files follow art/BRIEF-batch-4.md: <slug>-<width>.webp for each width, and <slug>-shadow.webp.
  const objects = JSON.parse(read(join(ROOT, "art", "objects", "manifest.json"))).objects ?? {};
  for (const [name, o] of Object.entries(objects)) {
    const files = [...(o.widths ?? []).map((w) => `${name}-${w}.webp`), `${name}-shadow.webp`];
    const missing = files.filter((f) => !existsSync(join(ROOT, "art", "objects", f)));
    if (!/^[a-z-]+$/.test(name) || (o.widths ?? []).length === 0 || missing.length > 0) throw new Error(`art/objects/manifest.json: ${name} needs widths and the files ${missing.join(", ") || files.join(", ")} in art/objects.`);
  }
  copyDir(join(ROOT, "art", "objects"), join(to, "objects"), (n) => n.endsWith(".webp"));
  // Notebook covers (art batch 5) for the landing page's marketplace shelf: the 450 px WebP of each, where it exists.
  const coversDir = join(ROOT, "art", "covers");
  const coverList = existsSync(join(coversDir, "manifest.json")) ? (JSON.parse(read(join(coversDir, "manifest.json"))).covers ?? []) : [];
  const covers = coverList.map((c) => c.name).filter((n) => /^cover-[a-z]+$/.test(n) && existsSync(join(coversDir, `${n}-450.webp`)));
  if (covers.length > 0) copyDir(coversDir, join(to, "covers"), (n) => n.endsWith("-450.webp"));
  const manifest = JSON.parse(read(join(ROOT, "art", "web", "manifest.json")));
  const pick = (group) => Object.fromEntries(Object.entries(group).map(([slug, a]) => [slug, { width: a.width, height: a.height, widths: a.widths }]));
  const body = [
    "// GENERATED by scripts/gen-data.mjs from art/web/manifest.json. Do not edit by hand. Run pnpm gen.",
    "export type ArtSize = { width: number; height: number; widths: readonly number[] };",
    `export const CUTOUTS = ${JSON.stringify(pick(manifest.cutouts))} as const satisfies Record<string, ArtSize>;`,
    `export const SCENES = ${JSON.stringify(pick(manifest.scenes))} as const satisfies Record<string, ArtSize>;`,
    "export type CutoutSlug = keyof typeof CUTOUTS;",
    "export type SceneSlug = keyof typeof SCENES;",
    `export const COVERS: readonly string[] = ${JSON.stringify(covers)};`,
    `export const OBJECT_RASTERS: Record<string, { widths: readonly number[] }> = ${JSON.stringify(Object.fromEntries(Object.entries(objects).map(([n, o]) => [n, { widths: [...o.widths].sort((a, b) => a - b) }])))};`,
    "",
  ].join("\n");
  return writeIfChanged(join(ROOT, "src", "art.generated.ts"), body);
}

/** Taku mode packages (modes/<slug>/), checked by tests/unit/modes.test.ts with convex/modes/package.ts. */
export function buildModes() {
  const modes = {};
  for (const slug of listDirs(join(ROOT, "modes"))) {
    const dir = join(ROOT, "modes", slug);
    const text = read(join(dir, "mode.md"));
    const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (match === null) throw new Error(`modes/${slug}/mode.md needs frontmatter.`);
    modes[slug] = { frontmatter: parseYaml(match[1]), body: match[2].trim(), listing: JSON.parse(read(join(dir, "listing.json"))) };
  }
  return modes;
}

/** Widget packages (widgets/<slug>/), checked by tests/unit/widgets.test.ts. */
export function buildWidgets() {
  const widgets = {};
  for (const slug of listDirs(join(ROOT, "widgets"))) {
    const dir = join(ROOT, "widgets", slug);
    const text = read(join(dir, "widget.md"));
    const match = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (match === null) throw new Error(`widgets/${slug}/widget.md needs frontmatter.`);
    widgets[slug] = { frontmatter: parseYaml(match[1]), body: match[2].trim(), listing: JSON.parse(read(join(dir, "listing.json"))) };
  }
  return widgets;
}

export function build() {
  const prompts = {};
  for (const name of listFiles(join(ROOT, "convex", "ai", "prompts"), (n) => n.endsWith(".md"))) {
    prompts[name.replace(/\.md$/, "")] = read(join(ROOT, "convex", "ai", "prompts", name));
  }
  const includeFixtures = process.env.TAKU_GEN_FIXTURES !== "0";
  const fixtures = includeFixtures ? buildFixtures() : {};
  const modes = buildModes();
  const widgets = buildWidgets();
  const a = writeIfChanged(
    join(OUT_DIR, "generated.ts"),
    tsModule('import type { ModePackageData, WidgetPackageData } from "./types";', [
      ["PROMPTS", "Record<string, string>", prompts],
      ["MODES", "Record<string, ModePackageData>", modes],
      ["WIDGETS", "Record<string, WidgetPackageData>", widgets],
    ]),
  );
  const b = writeIfChanged(
    join(OUT_DIR, "fixtures.generated.ts"),
    tsModule('import type { AiFixture } from "./types";', [["AI_FIXTURES", "Record<string, AiFixture>", fixtures]]),
  );
  const c = buildArt();
  return { changed: a || b || c, prompts: Object.keys(prompts).length, fixtures: Object.keys(fixtures).length, includeFixtures };
}

if (process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1]) {
  const summary = build();
  console.log(
    `gen: ${summary.prompts} prompts, ${summary.fixtures} AI fixtures${summary.includeFixtures ? "" : " (fixtures excluded)"}${summary.changed ? "" : " (unchanged)"}`,
  );
}
